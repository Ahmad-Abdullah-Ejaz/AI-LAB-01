# AI Lab 01: Python Basics & Standard I/O
# Basic input, output, and statement formatting

# 1. Basic print
print("Hello World!")

# 2. Taking integer input
# input() returns string by default, so we cast it with int()
num = int(input("Enter a number: "))
print("Number:", num)

# 3. Taking string input
string_val = input("Enter a string: ")
print("String:", string_val)

# 4. Multiple statements on single line (using semicolon)
# Note: Semicolons work in Python, but PEP 8 prefers separate lines for readability
print("Statement1")
print("Statement2")
print("Statement3")
